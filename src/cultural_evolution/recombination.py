"""
Recombinant Patent Model: Modular Innovation & Cumulative Technological Evolution.
Based on Mathieu Charbonneau (2015, 2018) & Alexey Koshevoy (2023, 2024).
"""

from typing import Dict, List, Optional, Tuple
import numpy as np


class RecombinantPatentModel:
    """
    Simulates cumulative technological evolution through modular recombination and
    preferential citation dynamics.

    In this model, new technological artifacts (patents) are generated by recombining
    existing modules and introducing novel interfaces. Citation weights follow:
        W_j = (Citations_j + 1)^alpha * (Quality_j)^beta

    Parameters
    ----------
    initial_patents : int, default=20
        Number of foundational patents at generation 0.
    total_steps : int, default=500
        Number of technological innovation events.
    alpha_cit : float, default=1.0
        Preferential attachment / cumulative advantage exponent (Yule-Simon).
    beta_quality : float, default=1.0
        Content / intrinsic technological utility bias exponent.
    mutation_rate : float, default=0.05
        Probability of introducing a de novo module rather than recombining.
    seed : int, default=42
        Random seed for reproducibility.
    """

    def __init__(
        self,
        initial_patents: int = 20,
        total_steps: int = 500,
        alpha_cit: float = 1.0,
        beta_quality: float = 1.0,
        mutation_rate: float = 0.05,
        seed: int = 42,
    ) -> None:
        self.initial_patents = initial_patents
        self.total_steps = total_steps
        self.alpha_cit = alpha_cit
        self.beta_quality = beta_quality
        self.mutation_rate = mutation_rate
        self.seed = seed

    def simulate(self) -> Dict[str, np.ndarray]:
        """
        Execute technological recombination simulation.

        Returns
        -------
        Dict[str, np.ndarray]
            Dictionary containing citations, qualities, patent_modules, and cumulative_patents.
        """
        rng = np.random.default_rng(self.seed)

        citations = np.zeros(self.initial_patents + self.total_steps, dtype=int)
        qualities = np.zeros(self.initial_patents + self.total_steps, dtype=float)

        qualities[: self.initial_patents] = rng.uniform(1.0, 3.0, size=self.initial_patents)

        patent_modules = [
            list(rng.choice(10, size=2, replace=False))
            for _ in range(self.initial_patents)
        ]

        active_patents = self.initial_patents
        max_module_id = 10

        for step in range(self.total_steps):
            cur_idx = self.initial_patents + step

            cit_weights = (citations[:active_patents] + 1.0) ** self.alpha_cit
            qual_weights = (qualities[:active_patents]) ** self.beta_quality
            weights = cit_weights * qual_weights
            probs = weights / np.sum(weights)

            num_parents = 2
            parents = rng.choice(active_patents, size=num_parents, p=probs, replace=False)

            citations[parents] += 1

            parent_mods = set(patent_modules[parents[0]] + patent_modules[parents[1]])
            if rng.random() < self.mutation_rate:
                parent_mods.add(max_module_id)
                max_module_id += 1

            patent_modules.append(list(parent_mods))

            q_inherited = max(qualities[parents])
            q_bonus = rng.exponential(scale=0.5)
            qualities[cur_idx] = q_inherited + q_bonus

            active_patents += 1

        total_patents = active_patents
        cit_counts = citations[:total_patents]
        qual_counts = qualities[:total_patents]

        sorted_cits = np.sort(cit_counts)[::-1]
        ranks = np.arange(1, len(sorted_cits) + 1)

        return {
            "citations": cit_counts,
            "qualities": qual_counts,
            "ranks": ranks,
            "sorted_citations": sorted_cits,
            "patent_modules": patent_modules,
            "total_modules": max_module_id,
        }
